import os
from PIL import Image

orig_path = "../frontend/public/bg-vijayanagara-toymaker.jpg"
gen_path = os.environ.get("GEN_PATH", "../frontend/public/bg-vijayanagara-toymaker-clean.jpg")
out_path = "../frontend/public/bg-vijayanagara-toymaker.jpg"

if not os.path.exists(orig_path):
    print("Original not found.")
    exit(1)
if not os.path.exists(gen_path):
    print("Generated not found.")
    exit(1)

orig = Image.open(orig_path).convert("RGB")
gen = Image.open(gen_path).convert("RGB")

# Ensure same size
if orig.size != gen.size:
    gen = gen.resize(orig.size, Image.Resampling.LANCZOS)

width, height = orig.size

# We want to keep the left side (up to 75% width) from the original
# And use the right 25% from the generated image (where the people were removed)
# We will create an alpha mask for blending.
mask = Image.new("L", orig.size, 0)
for x in range(width):
    for y in range(height):
        # Start transition at 70% width, full generated by 75%
        if x < int(width * 0.70):
            val = 0
        elif x > int(width * 0.75):
            val = 255
        else:
            # Linear interpolation
            ratio = (x - width * 0.70) / (width * 0.05)
            val = int(ratio * 255)
        mask.putpixel((x, y), val)

# Apply blend
result = Image.composite(gen, orig, mask)

# Save result
result.save(out_path, quality=95)
print("Successfully blended images and saved over original.")
